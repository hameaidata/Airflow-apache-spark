CREATE TABLE PARAMETROS_TABLA AS
	WITH PARAMETROS AS
	(
		SELECT
			CAST(@v_fecha_proceso AS DATE) AS FECHA_PROCESO,
			@p_dias AS NUM_DIAS
	),

	FECHA_RESTADA AS
	(
		SELECT
			FECHA_PROCESO,
			DATE_SUB(FECHA_PROCESO, INTERVAL NUM_DIAS DAY) AS FECHA_CALCULADA
		FROM PARAMETROS
	),

	FECHA_HABIL_BASE AS
	(
		SELECT
			MAX(C.FEC_CALENDARIO) AS FECHA_INICIO
		FROM FECHA_RESTADA F
		JOIN BDS_CALENDARIOS C
			ON C.COD_CALENDARIO = 1
		AND C.IND_DIA_HABIL = 'S'
		AND C.FEC_CALENDARIO <= F.FECHA_CALCULADA
	),

	INICIO_MES AS
	(
		SELECT
			DATE_FORMAT(FECHA_CALCULADA,'%Y-%m-01') AS FECHA_INICIO_MES
		FROM FECHA_RESTADA
	)

	SELECT
		P.FECHA_PROCESO AS FECHA_FIN,
		I.FECHA_INICIO_MES,
		H.FECHA_INICIO
	FROM PARAMETROS P
	CROSS JOIN INICIO_MES I
	CROSS JOIN FECHA_HABIL_BASE H;
	
	
