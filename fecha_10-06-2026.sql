	CREATE TABLE TABLA_FINAL_SIN_NOMBRE AS 
	WITH BASE_14_1_VIGENTE_MO AS (
		SELECT ID_OPERACION_CIERRE,COD_RUBRO, FECHA_PROCESO,MTO_SALDO_MO AS MTO_SALDO_VIGENTE_MO, MTO_SALDO_MN AS MTO_SALDO_VIGENTE_MN FROM UNION_ALL_TABLE_1
			WHERE SUBSTR(COD_RUBRO,1,4) LIKE '14_1' GROUP BY ID_OPERACION_CIERRE, FECHA_PROCESO, COD_RUBRO
	),
	BASE_14_3_MTO_RESTRUCTURADO_MO AS (
		SELECT  ID_OPERACION_CIERRE,COD_RUBRO,FECHA_PROCESO,MTO_SALDO_MO AS MTO_SALDO_RESTRUCTURADO_MO,  MTO_SALDO_MN AS MTO_SALDO_RESTRUCTURADO_MN  FROM UNION_ALL_TABLE_1 pc 
		WHERE SUBSTR(COD_RUBRO,1,4) LIKE '14_3' GROUP BY ID_OPERACION_CIERRE, FECHA_PROCESO,COD_RUBRO ),
	MTO_14_4_SALDO_REFINANCIADO_MO AS (
		SELECT    ID_OPERACION_CIERRE,COD_RUBRO, FECHA_PROCESO,MTO_SALDO_MO AS MTO_SALDO_REFINANCIADO_MO , MTO_SALDO_MN AS MTO_SALDO_REFINANCIADO_MN  FROM UNION_ALL_TABLE_1 pc 
		WHERE SUBSTR(COD_RUBRO,1,4) LIKE '14_4' GROUP BY ID_OPERACION_CIERRE, FECHA_PROCESO,COD_RUBRO
	),
	BASE_14_5_MTO_VENCIDO_MO AS (
		SELECT   ID_OPERACION_CIERRE,COD_RUBRO,FECHA_PROCESO,MTO_SALDO_MO AS MTO_SALDO_VENCIDO_MO, MTO_SALDO_MN AS MTO_SALDO_VENCIDO_MN  FROM UNION_ALL_TABLE_1 pc 
		WHERE SUBSTR(COD_RUBRO,1,4) LIKE '14_5'GROUP BY ID_OPERACION_CIERRE, FECHA_PROCESO,COD_RUBRO ),
	BASE_14_6_MTO_JUDICIA_MO AS (
		SELECT    ID_OPERACION_CIERRE,COD_RUBRO,FECHA_PROCESO,MTO_SALDO_MO AS MTO_SALDO_JUDIAL_MO, MTO_SALDO_MN AS MTO_SALDO_JUDICIAL_MN  FROM UNION_ALL_TABLE_1 pc 
		WHERE SUBSTR(COD_RUBRO,1,4) LIKE '14_6' GROUP BY ID_OPERACION_CIERRE, FECHA_PROCESO,COD_RUBRO
	),
	BASE_TABLA AS (
		SELECT DISTINCT 
			bt.ID_OPERACION_CIERRE,
			bt.FECHA_PROCESO,
			bt.COD_EMPRESA,
			bt.COD_SUCURSAL,
			bt.COD_RUBRO,
			bt.COD_MONEDA,
			bt.COD_PAPEL,
			bt.NUM_CUENTA_BT,
			bt.COD_OPERACION,
			bt.COD_EJECUTIVO,
			bt.COD_SUB_OPERACION,
			bt.COD_TIPO_OPERACION,
			bt.COD_MODULO,
			bt.FEC_VENCIMIENTO,
			bt.FEC_VALOR,
			bt.IND_CATEGORIA_RIESGO,
			bt.COD_ACTI_BCO_CENTRAL,
			bt.COD_PRODUCTO,
			bt.MTO_SALDO_ORIGEN,
			bt.MTO_SALDO_MN,
			bt.MTO_SALDO_ME,
			bt.MTO_SALDO_MO,
			bt.MTO_INTERES,
			bt.MTO_PREVISIONES,
			bt.FUENTE,
			bt.IND_DIA_HABIL,
			bt.FECHA_CARGA,
			bt.BATCH_ID
		FROM UNION_ALL_TABLE_1 bt WHERE LEFT(bt.COD_RUBRO, 4) IN (
		'1401','1403','1404','1405','1406',
		'1411','1413','1414','1415','1416',
		'1421','1423','1424','1425','1426'
	))
	SELECT 
		bt.ID_OPERACION_CIERRE,
		bt.FECHA_PROCESO,
		bt.COD_EMPRESA,
		bt.COD_SUCURSAL,
		bt.COD_RUBRO,
		bt.COD_MONEDA,
		bt.COD_PAPEL,
		bt.NUM_CUENTA_BT,
		bt.COD_OPERACION,
		bt.COD_EJECUTIVO,
		bt.COD_SUB_OPERACION,
		bt.COD_TIPO_OPERACION,
		bt.COD_MODULO,
		bt.FEC_VENCIMIENTO,
		bt.FEC_VALOR,
		bt.IND_CATEGORIA_RIESGO,
		bt.COD_ACTI_BCO_CENTRAL,
		bt.COD_PRODUCTO,
		bt.MTO_SALDO_ORIGEN,
		bt.MTO_SALDO_MN,
		bt.MTO_SALDO_ME,
		bt.MTO_SALDO_MO,
		bt.MTO_INTERES,
		bt.MTO_PREVISIONES,
		COALESCE(bv.MTO_SALDO_VIGENTE_MO, 0) MTO_SALDO_VIGENTE_MO,
		COALESCE(bres.MTO_SALDO_RESTRUCTURADO_MO,0) MTO_SALDO_RESTRUCTURADO_MO,
		COALESCE(bref.MTO_SALDO_REFINANCIADO_MO ,0) MTO_SALDO_REFINANCIADO_MO,
		COALESCE(bven.MTO_SALDO_VENCIDO_MO,0) MTO_SALDO_VENCIDO_MO,
		COALESCE(bjud.MTO_SALDO_JUDIAL_MO,0) MTO_SALDO_JUDIAL_MO,
		-- 
		COALESCE(bv.MTO_SALDO_VIGENTE_MN, 0) MTO_SALDO_VIGENTE_MN,
		COALESCE(bres.MTO_SALDO_RESTRUCTURADO_MN,0) MTO_SALDO_RESTRUCTURADO_MN,
		COALESCE(bref.MTO_SALDO_REFINANCIADO_MN ,0) MTO_SALDO_REFINANCIADO_MN,
		COALESCE(bven.MTO_SALDO_VENCIDO_MN,0) MTO_SALDO_VENCIDO_MN,
		COALESCE(bjud.MTO_SALDO_JUDICIAL_MN,0) MTO_SALDO_JUDICIAL_MN,
		bt.FUENTE,
		bt.IND_DIA_HABIL,
		bt.FECHA_CARGA,
		bt.BATCH_ID
	FROM  BASE_TABLA bt
	LEFT JOIN BASE_14_1_VIGENTE_MO bv ON bt.ID_OPERACION_CIERRE = bv.ID_OPERACION_CIERRE   and bt.FECHA_PROCESO = bv.FECHA_PROCESO and bt.COD_RUBRO = bv.COD_RUBRO
	LEFT JOIN BASE_14_3_MTO_RESTRUCTURADO_MO bres ON bt.ID_OPERACION_CIERRE = bres.ID_OPERACION_CIERRE  and bt.FECHA_PROCESO = bres.FECHA_PROCESO and bt.COD_RUBRO = bres.COD_RUBRO
	LEFT JOIN MTO_14_4_SALDO_REFINANCIADO_MO bref ON bt.ID_OPERACION_CIERRE = bref.ID_OPERACION_CIERRE  and bt.FECHA_PROCESO = bref.FECHA_PROCESO and bt.COD_RUBRO = bref.COD_RUBRO
	LEFT JOIN BASE_14_5_MTO_VENCIDO_MO bven ON bt.ID_OPERACION_CIERRE = bven.ID_OPERACION_CIERRE and bt.FECHA_PROCESO = bven.FECHA_PROCESO and bt.COD_RUBRO = bven.COD_RUBRO
	LEFT JOIN BASE_14_6_MTO_JUDICIA_MO bjud ON bt.ID_OPERACION_CIERRE = bjud.ID_OPERACION_CIERRE and bt.FECHA_PROCESO = bjud.FECHA_PROCESO and bt.COD_RUBRO = bjud.COD_RUBRO;

