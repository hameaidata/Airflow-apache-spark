 WITH BASE AS (
    SELECT
        ID_OPERACION_CIERRE,
        MAX(FECHA_PROCESO) AS FECHA_PROCESO,
        SUM(TOTAL_SALDO_MN) /
        DAY(LAST_DAY(MAX(FECHA_PROCESO))) AS TOTAL_AVG_SALDO_MN
    FROM BDS_SALDOS_OPERATIVOS_HB
    GROUP BY
        YEAR(FECHA_PROCESO),
        MONTH(FECHA_PROCESO),
        ID_OPERACION_CIERRE
),
BASE_2 AS (
    SELECT
        ID_OPERACION_CIERRE,
        FECHA_PROCESO,
        TOTAL_AVG_SALDO_MN
    FROM BDS_SALDOS_OPERATIVOS_HB
    WHERE FECHA_PROCESO IN (
        '2026-01-31',
        '2026-02-28',
        '2026-03-31',
        '2026-04-30',
        '2026-05-31',
        '2026-06-30'
    )
)
SELECT
    A.ID_OPERACION_CIERRE,
    A.FECHA_PROCESO,
    A.TOTAL_AVG_SALDO_MN AS TOTAL_AVG_BASE,
    B.TOTAL_AVG_SALDO_MN AS TOTAL_AVG_BASE_2,
    ABS(ROUND(A.TOTAL_AVG_SALDO_MN,3)  - ROUND( B.TOTAL_AVG_SALDO_MN,3)) AS DIFERENCIA
FROM BASE A
INNER JOIN BASE_2 B
    ON A.ID_OPERACION_CIERRE = B.ID_OPERACION_CIERRE
   AND A.FECHA_PROCESO = B.FECHA_PROCESO
WHERE IFNULL(A.TOTAL_AVG_SALDO_MN,0)
    <> IFNULL(B.TOTAL_AVG_SALDO_MN,0)
ORDER BY
	ABS(ROUND(A.TOTAL_AVG_SALDO_MN,3)  - ROUND( B.TOTAL_AVG_SALDO_MN,3))
    DESC
    

